function coauthorTask(kind) {
  switch (kind) {
    case "ideas":
      return "Дай 3 разных варианта, куда двигать текст дальше. Каждый — одной-двумя фразами, по сути события или поворота, а не общими словами. Варианты должны отличаться друг от друга по существу.";
    case "critique":
      return "Разбери текст: что не работает и почему. Максимум 4 пункта, самое важное первым. По каждому — что конкретно сделать. Если что-то держит текст хорошо, скажи об этом одной строкой, без комплиментов.";
    case "continue":
      return "Предложи 2 варианта продолжения — по абзацу каждый, голосом и ритмом автора, без объяснений и заголовков. Начинай сразу с нового: не повторяй и не пересказывай последние предложения автора. Раздели варианты строкой из трёх дефисов: ---";
    case "hole":
      return "Найди дыры: что в тексте не сходится, что осталось необъяснённым, где читатель потеряется. До 4 пунктов, самое опасное первым.";
    default:
      return "";
  }
}

function styleHint(style) {
  return (STYLES[style] || STYLES.auto).hint;
}

/**
 * @param {{raw: string, context?: string, style?: string, instruction?: string, mode?: "chunk"|"full"}} p
 */
export function buildPrompt(p) {
  if (p.mode === "coauthor") return buildCoauthorPrompt(p);
  const style = styleHint(p.style);
  const instruction = (p.instruction || "").trim();
  const context = (p.context || "").trim();
  const raw = p.raw;

  if (p.mode === "full") {
    const parts = [
      "Перед тобой уже готовый текст целиком. Перечитай его и приведи в порядок как единое целое: связность, знаки, абзацы, повторы.",
      `Стиль: ${style}`,
    ];
    if (instruction) parts.push(`Отдельное указание автора: ${instruction}`);
    parts.push("", "<текст>", raw, "</текст>", "", "Верни только готовый текст.");
    return { system: SYSTEM, user: parts.join("\n") };
  }

  const parts = [];
  if (context) {
    parts.push(
      "Вот конец уже готового текста — он нужен только для контекста, переписывать и повторять его не надо:",
      "<уже_написано>",
      context,
      "</уже_написано>",
      ""
    );
  }
  parts.push(
    "Новый кусок сырого распознавания — его и надо превратить в текст:",
    "<распознано>",
    raw,
    "</распознано>",
    "",
    `Стиль: ${style}`
  );
  if (instruction) parts.push(`Отдельное указание автора: ${instruction}`);
  parts.push("", "Верни только готовое продолжение текста, без повторения того, что уже написано.");
  return { system: SYSTEM, user: parts.join("\n") };
}

/**
 * Соавтор: видит текст целиком (у длинного — начало и конец) и отвечает на просьбу автора.
 * @param {{raw: string, request?: string, kind?: string, instruction?: string}} p
 */
function buildCoauthorPrompt(p) {
  const text = (p.raw || "").trim();
  const request = (p.request || "").trim();
  const task = coauthorTask(p.kind);
  const instruction = (p.instruction || "").trim();

  const parts = [];
  if (text) {
    const long = text.length > 6000;
    parts.push("Текст автора" + (long ? " (начало и конец — середина опущена)" : "") + ":", "<текст>");
    parts.push(long ? `${text.slice(0, 1200)}\n\n[...]\n\n${text.slice(-4800)}` : text);
    parts.push("</текст>", "");
  } else {
    parts.push("Автор пока ничего не написал — работай от того, что он скажет.", "");
  }

  if (request) parts.push("Автор просит:", request, "");
  if (task) parts.push(task, "");
  if (instruction) parts.push(`Постоянное указание автора: ${instruction}`, "");
  if (!request && !task) parts.push("Скажи по этому тексту то, что автору полезнее всего услышать сейчас.", "");

  return { system: COAUTHOR_SYSTEM, user: parts.join("\n").trim() };
}
